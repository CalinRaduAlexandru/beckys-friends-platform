const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manual = JSON.parse(fs.readFileSync(path.join(root, 'data', 'manual.json'), 'utf8'));
const workspaces = JSON.parse(fs.readFileSync(path.join(root, 'data', 'workspaces.json'), 'utf8'));
const styles = { css: fs.readFileSync(path.join(root, 'data', 'custom.css'), 'utf8') };
const literal = value => JSON.stringify(value).replace(/'/g, "''");
const output = `-- Generated by npm run supabase:seed:generate.\ninsert into public.app_documents (key, payload) values\n  ('manual', '${literal(manual)}'::jsonb),\n  ('styles', '${literal(styles)}'::jsonb),\n  ('workspaces', '${literal(workspaces)}'::jsonb)\non conflict (key) do update set payload = excluded.payload, updated_at = now();\n`;

fs.mkdirSync(path.join(root, 'supabase'), { recursive: true });
fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), output);
console.log('Generated supabase/seed.sql');

