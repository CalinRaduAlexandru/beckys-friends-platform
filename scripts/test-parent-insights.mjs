import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { normalizeEvents, buildInsights } from '../src/parent-insights.mjs';

const session = randomUUID(), visit = randomUUID();
const event = (event_name, details = {}, overrides = {}) => ({id:randomUUID(),session_id:session,visit_id:visit,activity_id:'intrebari-profunde',event_name,occurred_at:new Date().toISOString(),viewport:'landscape',display_mode:'browser',...details,...overrides});
const options = ['safe','medium','wildcard'].map(id => ({id,text:`Întrebarea ${id}`}));
const raw = [event('info_view'),event('activity_start',{visible_ms:1000,resumed:false}),event('screen_view',{screen:'funny-experience'}),event('choice_view',{set_id:'one',options}),event('choice_selected',{set_id:'one',question_id:'safe'}),event('choice_view',{set_id:'two',options}),event('choice_skip',{set_id:'two'}),event('choice_view',{set_id:'three',options}),event('activity_complete',{visible_ms:11000}),event('activity_exit',{visible_ms:21000})];
const rows=normalizeEvents({events:raw});
let report=buildInsights([...rows,rows[4]]);
assert.equal(report.totals.events,10,'retry must not double count');
assert.equal(report.activities[0].starts,1);
assert.equal(report.activities[0].completed,1);
assert.equal(report.activities[0].exits,0,'completed return is not abandonment');
assert.equal(report.activities[0].median_visible_ms,10000,'exclude info and time after completion');
const q=report.questions.find(q=>q.question_id==='safe');
assert.deepEqual([q.shown,q.chosen,q.skipped,q.unresolved,q.choice_rate],[3,1,1,1,33.3]);
assert.equal(report.questions.find(q=>q.question_id==='medium').other,1);
assert.equal(q.sufficient,false);
assert.equal(report.activities[0].skip_rate,50,'skip denominator includes decisions only');
report=buildInsights(normalizeEvents({events:[event('activity_start'),event('visibility_hidden'),event('visibility_visible')]}));
assert.equal(report.activities[0].interrupted,0,'foreground return cancels interruption');
assert.equal(report.activities[0].open,1);
report=buildInsights(normalizeEvents({events:[event('activity_complete')]}));
assert.equal(report.activities[0].completed,0,'no completion numerator without a start in window');
const privateEvent=normalizeEvents({events:[event('help_used',{profile_name:'PRIVATE',answer:'PRIVATE',action:'data-sound-forgot'})]})[0];
assert(!JSON.stringify(privateEvent).includes('PRIVATE'));
assert.throws(()=>normalizeEvents({events:[event('choice_view',{set_id:'x',options:[options[0],options[0]]})]}));
assert.throws(()=>normalizeEvents({events:[event('invented')]}));
const source=readFileSync(new URL('../public/parents-tablet.js',import.meta.url),'utf8');
for(const match of source.matchAll(/track\('([^']+)'/g)) normalizeEvents({events:[event(match[1])]});

